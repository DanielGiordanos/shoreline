"""Build Flow's three script files from their pieces (n389).
python3 build_flow.py SITE_DIR [--check]

Flow's code lives in SITE/_source/flow/, one small file per piece, named feature.piece.js (drawer.fill-drawer.js,
care-team.care-team.js, hig.n370-sheets-and-windows.js ...). order.json lists the pieces of each built file in the order
they run. This tool joins them into assets/flow/app.js, layers.js and layers2.js, the files the page loads.

- A piece of app.js is joined as it is.
- A piece of layers.js or layers2.js is a block: it gets its heading ("k of N - title") and runs inside its own
  try{ ... }catch, so a block that throws never stops the next one ("wrap": false keeps a block as written, for the
  three whose page-wide declarations sit outside the try).
- The order in order.json is the order the code runs. Moving a piece changes behaviour: a layer added later is outermost.

Never edit the built files: each carries the SHA-256 of its body, and this tool (and the seal, which runs it first)
refuses to overwrite a built file that was changed by hand. INDEX.md, also written here, lists every piece by feature and
every function that has layers with the pieces that add them.
"""
import sys, os, re, json, hashlib

BUILT = ('app.js', 'layers.js', 'layers2.js')
CATCH = '}catch(e){setTimeout(function(){throw e})}'
HEADS = {
    'app.js': """/* Pravix Flow — app.js. BUILT by _ci/build_flow.py from the pieces in _source/flow/ (order.json lists them in order).
   Do not edit this file. Edit the piece, then run  python3 _ci/seal_csp.py .  (it rebuilds this file, then refreshes
   the ?v= in index.html and the content policy). This is Flow's main script; layers.js and layers2.js follow it.
   body sha256: %s */
""",
    'layers.js': """/* Pravix Flow — layers.js. BUILT by _ci/build_flow.py from the pieces in _source/flow/ (order.json lists them in order).
   Do not edit this file. Edit the piece, then run  python3 _ci/seal_csp.py .
   The blocks that follow the main script (assets/flow/app.js), up to where the Yakuri library loads, in the order they run.
   A block that throws doesn't stop the ones after it: it runs inside try/catch and the error is thrown again on its own,
   so it still shows in the console. What a block declares for the whole page stays outside the try.
   body sha256: %s */
""",
    'layers2.js': """/* Pravix Flow — layers2.js. BUILT by _ci/build_flow.py from the pieces in _source/flow/ (order.json lists them in order).
   Do not edit this file. Edit the piece, then run  python3 _ci/seal_csp.py .
   The blocks that follow the Yakuri library (assets/pvx-yakuri.js), in the order they run, each inside its own try/catch.
   body sha256: %s */
""",
}
HASH = re.compile(r'body sha256: ([0-9a-f]{16}) \*/\n')


def src_dir(site): return os.path.join(site, '_source', 'flow')
def has_source(site): return os.path.isfile(os.path.join(src_dir(site), 'order.json'))
def rd(*p):
    with open(os.path.join(*p), encoding='utf-8', newline='') as f: return f.read()
def digest(s): return hashlib.sha256(s.encode('utf-8')).hexdigest()[:16]
def feature(name): return name.split('.', 1)[0]


def order(site):
    o = json.loads(rd(src_dir(site), 'order.json')); files = []
    for b in BUILT:
        for p in o[b]: files.append(p if isinstance(p, str) else p['file'])
    if len(files) != len(set(files)): raise SystemExit('order.json lists a piece twice: ' + ', '.join(sorted(f for f in set(files) if files.count(f) > 1)))
    have = sorted(f for f in os.listdir(src_dir(site)) if f.endswith('.js'))
    missing = [f for f in files if f not in have]; stray = [f for f in have if f not in files]
    if missing: raise SystemExit('order.json names pieces that are not in _source/flow/: ' + ', '.join(missing))
    if stray: raise SystemExit('pieces in _source/flow/ that order.json does not list (they would never run): ' + ', '.join(stray))
    return o


def bodies(site):
    """the body of each built file: its pieces, joined"""
    o = order(site); S = src_dir(site); total = len(o['layers.js']) + len(o['layers2.js']); out = {}; k = 0
    out['app.js'] = ''.join(rd(S, p) for p in o['app.js'])
    for b in ('layers.js', 'layers2.js'):
        parts = []
        for p in o[b]:
            k += 1; code = rd(S, p['file'])
            parts.append('\n/* ━━━━━ %d of %d · %s ━━━━━ */\n' % (k, total, p['title']) + (('try{\n' + code + '\n' + CATCH + '\n') if p.get('wrap', True) else code))
        out[b] = ''.join(parts)
    return out


def built(site):
    return {b: HEADS[b] % digest(body) + body for b, body in bodies(site).items()}


def edited_by_hand(site):
    """built files on disk whose body no longer matches the hash in their own heading"""
    bad = []
    for b in BUILT:
        p = os.path.join(site, 'assets', 'flow', b)
        if not os.path.isfile(p): continue
        t = rd(p); m = HASH.search(t[:2000])
        if not m: continue            # a file from before n389: nothing to protect
        if digest(t[m.end():]) != m.group(1): bad.append(b)
    return bad


TABLE = re.compile(r'/\* (\w+) · its layers, innermost first: (.*?)   \(PVX-N387')   # the list written above each function (flow_t387 keeps it true)
WHO = re.compile(r"\bpvx(?:After|Before|Wrap)\((?:'\w+'|\w+),")                          # a piece that adds layers …
WHOTAG = re.compile(r",'(#\d+|n\d+[a-z0-9-]*)'\)")                                        # … signs each with its own tag
BASE = re.compile(r'(?m)^(?:async )?function (\w+)\$base\(')
NOTE = re.compile(r'/\*+\s*(.*?)\*/', re.S)


def index(site):
    """INDEX.md: the pieces by feature, and each function that has layers with the pieces that add them"""
    o = order(site); S = src_dir(site); rows = []; base = {}; layers = {}; tag = {}
    for b in BUILT:
        for n, p in enumerate(o[b]):
            f = p if isinstance(p, str) else p['file']; t = rd(S, f); m = NOTE.search(t[:1500])
            note = re.sub(r'\s+', ' ', m.group(1)).strip(' ═=─━-') if m else ''
            note = re.sub(r'^[═=─━\s]+', '', note)[:110].replace('|', '/')
            if b == 'app.js':   # a piece of the main script is best described by what it declares
                names = [x for x in re.findall(r'(?m)^(?:async )?function (\w+)\(', t)]
                if not names: names = re.findall(r'(?m)^(?:const|let|var) (\w+)', t)
                note = ', '.join(names[:7]) + (' … and %d more' % (len(names) - 7) if len(names) > 7 else '')
            rows.append((feature(f), f, b, n + 1, len(t.encode('utf-8')), note))
            for x in BASE.findall(t): base[x] = f
            for name, lst in TABLE.findall(t): layers[name] = [x.split(' ', 1)[1].rsplit(' ', 1) for x in lst.split(' · ')]
            if b != 'app.js' and WHO.search(t):
                for w in set(WHOTAG.findall(t)): tag.setdefault(w, f)
    L = ['# Flow: where the code is', '', 'Written by `_ci/build_flow.py`. Do not edit; it is rewritten on every build.', '',
         'Each piece is `feature.piece.js` in this folder. `order.json` lists them in the order they run.', '',
         '## Pieces by feature', '']
    feats = sorted(set(r[0] for r in rows))
    L.append('| Feature | Pieces | Size |'); L.append('| --- | ---: | ---: |')
    for ft in feats:
        rs = [r for r in rows if r[0] == ft]; L.append('| `%s` | %d | %d KB |' % (ft, len(rs), round(sum(r[4] for r in rs) / 1024)))
    for ft in feats:
        L += ['', '### ' + ft, '', '| Piece | Built into | Size | What is in it |', '| --- | --- | ---: | --- |']
        for r in sorted((r for r in rows if r[0] == ft), key=lambda r: (BUILT.index(r[2]), r[3])):
            L.append('| `%s` | %s, piece %d | %.1f KB | %s |' % (r[1], r[2], r[3], r[4] / 1024, r[5]))
    L += ['', '## Functions that have layers', '', 'The function itself is `NAME$base`, in the piece named first. The layers are in the order they were added (the last is outermost).', '',
          '| Function | Its own code | Layers, innermost first |', '| --- | --- | --- |']
    for name in sorted(layers):
        if name in base: L.append('| `%s` | `%s` | %s |' % (name, base[name], ' · '.join('`%s` %s' % (tag.get(w, w), k) for w, k in layers[name])))
    return '\n'.join(L) + '\n'


def build(site, write=True):
    """returns the names of the files that changed (or would change)"""
    bad = edited_by_hand(site)
    if bad:
        raise SystemExit('EDITED BY HAND: assets/flow/%s. Flow\'s code is in _source/flow/ (see INDEX.md there); these files are built from it.\n'
                         'Move the change into the piece it belongs to, restore the built file, and run the seal again.' % ', assets/flow/'.join(bad))
    want = built(site); want_index = index(site); changed = []
    for b, text in want.items():
        p = os.path.join(site, 'assets', 'flow', b)
        if not os.path.isfile(p) or rd(p) != text:
            changed.append('assets/flow/' + b)
            if write:
                with open(p, 'w', encoding='utf-8', newline='') as f: f.write(text)
    ip = os.path.join(src_dir(site), 'INDEX.md')
    if not os.path.isfile(ip) or rd(ip) != want_index:
        changed.append('_source/flow/INDEX.md')
        if write:
            with open(ip, 'w', encoding='utf-8', newline='') as f: f.write(want_index)
    return changed


if __name__ == '__main__':
    site = sys.argv[1]
    if not has_source(site): raise SystemExit('no _source/flow/order.json in ' + site)
    if '--check' in sys.argv:
        ch = build(site, write=False)
        print('built' if not ch else 'NOT BUILT: ' + ', '.join(ch) + ' differ from what _source/flow gives. Run python3 seal_csp.py ' + site); sys.exit(1 if ch else 0)
    ch = build(site); o = order(site)
    print('built', len(o['app.js']), '+', len(o['layers.js']), '+', len(o['layers2.js']), 'pieces ·', 'changed: ' + ', '.join(ch) if ch else 'nothing changed')
